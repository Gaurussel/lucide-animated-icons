import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const iconsDir = join(root, "src/icons");
const lucideImports = join(root, "node_modules/lucide-react/dist/esm/dynamicIconImports.js");
const check = process.argv.includes("--check");

export const toPascal = (name: string) =>
	name
		.split("-")
		.map((part) => part[0].toUpperCase() + part.slice(1))
		.join("");

const defs = new Set(
	readdirSync(iconsDir)
		.filter((file) => file.endsWith(".tsx"))
		.map((file) => file.slice(0, -".tsx".length)),
);

const lucide = [
	...readFileSync(lucideImports, "utf8").matchAll(/"([\w-]+)": \(\) => import\('\.\/icons\/([\w-]+)\.js'\)/g),
]
	.map(([, name, target]) => ({ name, target }))
	.sort((a, b) => a.name.localeCompare(b.name));

const missing = lucide.filter(({ target }) => !defs.has(target)).map(({ target }) => target);
const unknown = [...defs].filter((name) => !lucide.some(({ target }) => target === name));

const header = "// Generated by scripts/generate.ts. Do not edit.\n";

const iconsIndex =
	header +
	[...new Map(lucide.filter(({ target }) => defs.has(target)).map(({ name, target }) => [toPascal(name), target]))]
		.map(([exported, target]) => `export { default as ${exported} } from "./${target}.tsx";`)
		.join("\n") +
	"\n";

const loaders = `${header}import type { AnimatedIconLoader } from "./types.ts";

export const animatedIconLoaders = {
${lucide
	.filter(({ target }) => defs.has(target))
	.map(({ name, target }) => `\t"${name}": () => import("./icons/${target}.tsx"),`)
	.join("\n")}
} satisfies Record<string, AnimatedIconLoader>;

export type AnimatedIconName = keyof typeof animatedIconLoaders;
`;

const outputs = [
	[join(iconsDir, "index.ts"), iconsIndex],
	[join(root, "src/loaders.ts"), loaders],
] as const;

const read = (path: string) => {
	try {
		return readFileSync(path, "utf8");
	} catch {
		return "";
	}
};

if (unknown.length) console.error(`Not a lucide icon: ${unknown.join(", ")}`);
if (missing.length) console.error(`Not animated yet (${missing.length}): ${[...new Set(missing)].join(", ")}`);

if (check) {
	const stale = outputs.filter(([path, content]) => read(path) !== content).map(([path]) => path);
	if (stale.length) console.error(`Out of date, run \`bun run generate\`: ${stale.join(", ")}`);
	if (stale.length || unknown.length) process.exit(1);
} else {
	for (const [path, content] of outputs) writeFileSync(path, content);
	console.log(`${defs.size} icons, ${lucide.length - defs.size} aliases`);
}
